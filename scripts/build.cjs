'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const version=require(path.join(root,'manifest.json')).version;
if(!/^\d+\.\d+\.\d+$/.test(version)||require(path.join(root,'package.json')).version!==version)throw Error('Version mismatch');
fs.writeFileSync(path.join(root,'cmd/host-manager/version_gen.go'),'// Code generated by scripts/build.cjs; DO NOT EDIT.\npackage main\n\nconst version = '+JSON.stringify(version)+'\n');
const source=fs.readFileSync(path.join(root,'src/viewer.html'),'utf8');
fs.writeFileSync(path.join(root,'viewer.html'),source.replaceAll('__BRIDGE_VERSION__',version).replace('/* HOST_CLIENT */',fs.readFileSync(path.join(root,'src/host-client.js'),'utf8')));

// Aide upload validation evaluates only index.js in an empty temporary directory.
// Inline the two local helpers while preserving the installed entry's __dirname.
function inlineModule(name) {
 const source=fs.readFileSync(path.join(root,name),'utf8');
 if (/require\(['"]\./.test(source)) throw Error('Unbundled helper dependency: '+name);
 return '(() => { const module = {exports: {}};\n'+source+'\nreturn module.exports; })()';
}
let entry=fs.readFileSync(path.join(root,'src/plugin.cjs'),'utf8');
for (const name of ['connection.cjs','quota.cjs']) entry=entry.replace("require('./"+name+"')",()=>inlineModule(name));
entry=entry.replace("require('./manifest.json').version",JSON.stringify(version));
if (/require\(['"]\./.test(entry)) throw Error('Plugin entry must be self-contained');
fs.writeFileSync(path.join(root,'index.js'),'// Generated by scripts/build.cjs from src/plugin.cjs; do not edit.\n'+entry);
